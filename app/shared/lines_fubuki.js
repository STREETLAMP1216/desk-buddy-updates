  const bags = {};
  function pick(kind, vars, rand) {
    const pool = LINES[kind] || [];
    if (!pool.length) return '';
    const r = rand || Math.random;
    if (!bags[kind] || !bags[kind].length) {
      bags[kind] = pool.map((_, i) => i).sort(() => r() - 0.5);
    }
    let s = pool[bags[kind].pop()];
    Object.entries(vars || {}).forEach(([k, v]) => { s = s.split('{' + k + '}').join(String(v)); });
    return s;
  }

